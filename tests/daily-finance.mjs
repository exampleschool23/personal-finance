import test from 'node:test';
import assert from 'node:assert/strict';
import {loadTS} from './helpers/load-ts.mjs';
const {scheduleDates,scheduleDueDate}=loadTS('lib/finance.ts');
const {dueReminders}=loadTS('lib/daily-finance.ts');
const {monthly}=loadTS('lib/finance.ts');
const {earningSourceSchema,selectEarningSource}=loadTS('lib/earning-sources.ts');
const id=n=>`67000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const entry=(n,kind,extra={})=>({id:id(n),name:kind,kind,currency:'USD',amount:100,quantity:1,cost:0,rate:0,date:'2026-09-01',frequency:'Once',notes:'',...extra});
const data=(records,extra={})=>({records,categories:[],goals:[],activity:[],occurrences:[],...extra});
test('schedules retain anchors, leap days, weekly intervals and exact monthly counts',()=>{
 assert.deepEqual(scheduleDates({date:'2026-01-31',frequency:'Monthly'},'2026-01-01','2026-03-31'),['2026-01-31','2026-02-28','2026-03-31']);
 assert.deepEqual(scheduleDates({date:'2024-02-29',frequency:'Yearly'},'2025-01-01','2028-12-31'),['2025-02-28','2026-02-28','2027-02-28','2028-02-29']);
 assert.deepEqual(scheduleDates({date:'2026-09-01',frequency:'Custom',recurrence_days:10,end_date:'2026-09-25'},'2026-09-05','2026-10-31'),['2026-09-11','2026-09-21']);
 assert.deepEqual(scheduleDates({date:'2026-09-01',frequency:'Custom',recurrence_days:0},'2026-09-01','2026-10-31'),[]);
 assert.equal(scheduleDueDate({date:'2026-09-01',frequency:'Fortnightly'},'2026-09-30'),'2026-09-29');
 assert.equal(monthly(entry(1,'Salary',{frequency:'Weekly'}),'2026-09'),500);
 assert.equal(monthly(entry(1,'Salary',{frequency:'Weekly',end_date:'2026-09-15'}),'2026-09'),300);
 assert.equal(monthly(entry(1,'Salary',{frequency:'Weekly',source_paused:true}),'2026-09'),0);
 const source={id:id(10),name:'Wages',kind:'Salary',currency:'USD',mode:'fixed',amount:100,frequency:'Custom',recurrence_days:10,start_date:'2026-09-01',end_date:null};
 assert.equal(earningSourceSchema.safeParse(source).success,true);
 assert.equal(earningSourceSchema.safeParse({...source,recurrence_days:0}).success,false);
 assert.equal(selectEarningSource(entry(20,'Salary',{date:'2026-09-21'}),source).earning_due_on,'2026-09-21');
});
test('reminders honor settlement, snooze and opt-out',()=>{
 const bill=entry(2,'Rent expense',{frequency:'Weekly'}),d=data([bill],{occurrences:[{record_id:bill.id,due_on:'2026-09-01',status:'paid'}]});
 const settings={enabled:true,days_ahead:7,snoozed:[]};
 assert.deepEqual(dueReminders(d,settings,'2026-09-01').map(r=>r.date),['2026-09-08']);
 assert.equal(dueReminders(d,{...settings,snoozed:[{key:bill.id+':2026-09-08',until:'2026-09-09'}]},'2026-09-08').length,1);
 assert.equal(dueReminders(d,{...settings,enabled:false},'2026-09-01').length,0);
});
